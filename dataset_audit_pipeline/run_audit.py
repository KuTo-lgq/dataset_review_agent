        "3. 你必须返回完整标签对象，至少包含：status、skip_reason、l2_relationship、l3_scene、l4_auxiliary_tags、ops_tags、service_actions、reasoning、confidence。\n"
        "4. 布尔字段必须是 true/false，customer_count 必须是整数。\n\n"
        f"命中的静态问题：{', '.join(issues)}\n"
        f"当前标签：{current_label}\n\n"
