def apply_rule_fix_to_label(label: dict[str, Any]) -> tuple[dict[str, Any], list[str]]:
    fixed = ensure_label_shape(label)
    changes: list[str] = []
    flat = flatten_label(fixed)
    l2 = fixed["l2_relationship"]
    l4 = fixed["l4_auxiliary_tags"]

    if flat.get("skip_reason") not in SKIP_REASON_VALUES:
        fixed["skip_reason"] = "OTHER"
        changes.append("normalize_skip_reason")
    if flat.get("l2_primary") not in L2_VALUES:
        l2["primary"] = "unknown"
        changes.append("normalize_l2_primary")
    if flat.get("group_gender") not in GROUP_GENDER_VALUES:
        l4["group_gender"] = "unknown"
        changes.append("normalize_group_gender")
    if flat.get("child_age_bucket") not in CHILD_AGE_VALUES:
        l4["child_age_bucket"] = "none"
        changes.append("normalize_child_age_bucket")
    customer_count = flat.get("customer_count")
    if not isinstance(customer_count, int) or customer_count < 0:
        l4["customer_count"] = 0
        changes.append("normalize_customer_count")
    if flat.get("status") == "SKIP":
        if flat.get("customer_count") not in {0, None}:
            l4["customer_count"] = 0
            changes.append("zero_customer_count_for_skip")
        if flat.get("l2_primary") not in {"unknown", "", None}:
            l2["primary"] = "unknown"
            changes.append("normalize_l2_for_skip")
    if flat.get("contains_child") is False and flat.get("child_age_bucket") not in {"none", "", None}:
        l4["child_age_bucket"] = "none"
        changes.append("clear_child_age_without_child")
    if flat.get("contains_elder") not in {True, False}:
        l4["contains_elder"] = False
        changes.append("normalize_contains_elder")
    if flat.get("young_group") not in {True, False}:
        l4["young_group"] = False
        changes.append("normalize_young_group")
    return fixed, changes


def should_send_to_auto_fix_model(issues: list[str]) -> bool:
    for issue in issues:
        prefix = issue.split(":", 1)[0].split("=", 1)[0]
        if prefix in AUTO_FIX_MODEL_ELIGIBLE_ISSUES:
            return True
    return False


