def ensure_dir(path: Path) -> None:
    path.mkdir(parents=True, exist_ok=True)


def save_json(path: Path, obj: Any) -> None:
    ensure_dir(path.parent)
    path.write_text(json.dumps(obj, ensure_ascii=False, indent=2), encoding="utf-8")


def save_jsonl(path: Path, rows: list[dict[str, Any]]) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8") as fh:
        for row in rows:
            fh.write(json.dumps(row, ensure_ascii=False) + "\n")


def save_csv(path: Path, rows: list[dict[str, Any]], fieldnames: list[str]) -> None:
    ensure_dir(path.parent)
    with path.open("w", encoding="utf-8-sig", newline="") as fh:
        writer = csv.DictWriter(fh, fieldnames=fieldnames)
        writer.writeheader()
        writer.writerows(rows)


def extract_meta(prompt: str) -> dict[str, str]:
    meta: dict[str, str] = {}
    for key in ("store_id", "scene_id", "captured_at", "order_id", "business_date"):
        match = re.search(rf"{re.escape(key)}:\s*(.+)", prompt)
        if match:
            meta[key] = match.group(1).strip()
    return meta


def load_rows(dataset_dir: Path, split_files: list[str]) -> list[Row]:
    rows: list[Row] = []
    for split_file in split_files:
        split = split_file.replace(".jsonl", "")
        path = dataset_dir / split_file
        with path.open("r", encoding="utf-8") as fh:
            for line_no, line in enumerate(fh, start=1):
                obj = json.loads(line)
                convs = obj.get("conversations", [])
                prompt = convs[0]["value"] if convs else ""
                raw_label = convs[1]["value"] if len(convs) > 1 else None
                label = None
                if isinstance(raw_label, str):
                    try:
                        parsed = json.loads(raw_label)
                        label = parsed if isinstance(parsed, dict) else None
                    except Exception:
                        label = None
                elif isinstance(raw_label, dict):
                    label = raw_label
                rows.append(
                    Row(
                        split=split,
                        line_no=line_no,
                        image=obj["image"],
                        prompt=prompt,
                        raw_label=raw_label,
                        label=label,
                        meta=extract_meta(prompt),
                    )
                )
    return rows


def flatten_label(label: dict[str, Any] | None) -> dict[str, Any]:
    if not isinstance(label, dict):
        return {}
    l2 = label.get("l2_relationship") or {}
    l3 = label.get("l3_scene") or {}
    l4 = label.get("l4_auxiliary_tags") or {}
    reasoning = label.get("reasoning")
    if isinstance(reasoning, list):
        reasoning = " | ".join(str(item) for item in reasoning)
    return {
        "status": label.get("status"),
        "skip_reason": label.get("skip_reason"),
        "l2_primary": l2.get("primary"),
        "l3_scene": l3.get("scene_tag"),
        "customer_count": l4.get("customer_count"),
        "group_gender": l4.get("group_gender"),
        "contains_child": l4.get("contains_child"),
        "child_age_bucket": l4.get("child_age_bucket"),
        "contains_elder": l4.get("contains_elder"),
        "young_group": l4.get("young_group"),
        "confidence": label.get("confidence"),
        "reasoning": reasoning,
    }


def ensure_label_shape(label: dict[str, Any] | None) -> dict[str, Any]:
    normalized = json.loads(json.dumps(label or {}, ensure_ascii=False))
    if not isinstance(normalized, dict):
        normalized = {}
    normalized.setdefault("status", "VALID")
    normalized.setdefault("skip_reason", "OTHER")
    normalized.setdefault("l2_relationship", {})
    normalized.setdefault("l3_scene", {})
    normalized.setdefault("l4_auxiliary_tags", {})
    normalized.setdefault("ops_tags", [])
    normalized.setdefault("service_actions", [])
    normalized.setdefault("reasoning", "")
    normalized.setdefault("confidence", 0.0)
    if not isinstance(normalized["l2_relationship"], dict):
        normalized["l2_relationship"] = {}
    if not isinstance(normalized["l3_scene"], dict):
        normalized["l3_scene"] = {}
    if not isinstance(normalized["l4_auxiliary_tags"], dict):
        normalized["l4_auxiliary_tags"] = {}
    normalized["l2_relationship"].setdefault("primary", "unknown")
    normalized["l3_scene"].setdefault("scene_tag", "")
    l4 = normalized["l4_auxiliary_tags"]
    l4.setdefault("customer_count", 0)
    l4.setdefault("group_gender", "unknown")
    l4.setdefault("contains_child", False)
    l4.setdefault("child_age_bucket", "none")
    l4.setdefault("contains_elder", False)
    l4.setdefault("young_group", False)
    return normalized


def static_issue_score(issues: list[str]) -> int:
    return sum(issue_weight(issue, STATIC_WEIGHTS) for issue in issues)


