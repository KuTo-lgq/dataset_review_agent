def load_font(size: int) -> Any:
    configured_font = os.environ.get("DATASET_AUDIT_FONT_PATH", "").strip()
    candidates: list[str] = []
    if configured_font:
        candidates.append(configured_font)
    candidates.extend(
        [
            "C:/Windows/Fonts/msyh.ttc",
            "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
            "/usr/share/fonts/truetype/liberation2/LiberationSans-Regular.ttf",
            "/System/Library/Fonts/PingFang.ttc",
        ]
    )
    if ImageFont is None:
        return None
    for candidate in candidates:
        path = Path(candidate)
        if not path.exists():
            continue
        try:
            return ImageFont.truetype(str(path), size=size)
        except Exception:
            continue
    try:
        return ImageFont.load_default()
    except Exception:
        return None


def wrap_line(text: str, width: int = 90) -> list[str]:
    return textwrap.wrap(text, width=width, break_long_words=True, break_on_hyphens=False) or [text]


def issue_weight(issue: str, mapping: dict[str, int]) -> int:
    for prefix, weight in mapping.items():
        if issue == prefix or issue.startswith(prefix + ":") or issue.startswith(prefix + "="):
            return weight
    return 20


def parse_time(value: str) -> datetime | None:
    if not value:
        return None
    text = value.strip().replace("Z", "+00:00").replace("/", "-")
    try:
        return datetime.fromisoformat(text)
    except Exception:
        pass
    for fmt in ("%Y-%m-%d %H:%M:%S", "%Y-%m-%dT%H:%M:%S", "%Y-%m-%dT%H:%M:%S.%f%z", "%Y-%m-%dT%H:%M:%S%z"):
        try:
            return datetime.strptime(text, fmt)
        except Exception:
            continue
    return None


def seconds_between(a: datetime | None, b: datetime | None) -> float | None:
    if a is None or b is None:
        return None
    return abs((b - a).total_seconds())


def static_issues(row: Row) -> list[str]:
    issues: list[str] = []
    image_path = Path(row.image)
    if not image_path.exists():
        issues.append("missing_image_file")

    if not isinstance(row.raw_label, str):
        issues.append(f"raw_label_type={type(row.raw_label).__name__}")
    if row.label is None:
        issues.append("label_not_json_object")
        return issues

    for field in TOP_LEVEL_FIELDS:
        if field not in row.label:
            issues.append(f"missing_top_field:{field}")

    for meta_key in ("order_id", "scene_id", "captured_at"):
        if not row.meta.get(meta_key):
            issues.append(f"missing_meta_field:{meta_key}")

    flat = flatten_label(row.label)
    status = flat.get("status")
    skip_reason = flat.get("skip_reason")
    l2_primary = flat.get("l2_primary")
    child_age = flat.get("child_age_bucket")
    group_gender = flat.get("group_gender")
    customer_count = flat.get("customer_count")
    contains_elder = flat.get("contains_elder")
    young_group = flat.get("young_group")

    if status not in STATUS_VALUES:
        issues.append(f"invalid_status:{status}")
    if skip_reason not in SKIP_REASON_VALUES:
        issues.append(f"invalid_skip_reason:{skip_reason}")
    if l2_primary not in L2_VALUES:
        issues.append(f"invalid_l2_primary:{l2_primary}")
    if group_gender not in GROUP_GENDER_VALUES:
        issues.append(f"invalid_group_gender:{group_gender}")
    if child_age not in CHILD_AGE_VALUES:
        issues.append(f"invalid_child_age_bucket:{child_age}")
    if customer_count is not None and not isinstance(customer_count, int):
        issues.append(f"invalid_customer_count_type:{type(customer_count).__name__}")
    if isinstance(customer_count, int) and customer_count < 0:
        issues.append("negative_customer_count")

    if status in {"VALID", "REVIEW"} and skip_reason not in {"OTHER", "", None}:
        issues.append("status_skip_inconsistent")
    if status == "SKIP":
        if customer_count not in (0, None):
            issues.append("skip_with_nonzero_customer_count")
        if l2_primary not in {"unknown", "", None}:
            issues.append("skip_with_non_unknown_l2")
    if flat.get("contains_child") is False and child_age not in {"none", "", None}:
        issues.append("contains_child_false_but_age_present")
    if flat.get("contains_child") is True and child_age in {"none", "", None}:
        issues.append("contains_child_true_but_age_none")
    if contains_elder not in {True, False, None}:
        issues.append("contains_elder_not_bool")
    if young_group not in {True, False, None}:
        issues.append("young_group_not_bool")

    return issues


def summarize_static(rows: list[Row]) -> tuple[dict[str, Any], dict[tuple[str, int], list[str]], list[dict[str, Any]]]:
    issue_counter: Counter[str] = Counter()
    row_issues: dict[tuple[str, int], list[str]] = defaultdict(list)
    status_counter: Counter[str] = Counter()
    skip_counter: Counter[str] = Counter()
    by_image: dict[str, list[Row]] = defaultdict(list)

    for row in rows:
        if row.label:
            flat = flatten_label(row.label)
            status_counter[str(flat.get("status"))] += 1
            skip_counter[str(flat.get("skip_reason"))] += 1
        issues = static_issues(row)
        for issue in issues:
            issue_counter[issue] += 1
            row_issues[(row.split, row.line_no)].append(issue)
        by_image[row.image].append(row)

    duplicate_conflicts = 0
    flagged_rows: list[dict[str, Any]] = []

    for image, image_rows in by_image.items():
        if len(image_rows) < 2:
            continue
        signatures = {canonical_signature(row) for row in image_rows}
        if len(signatures) > 1:
            duplicate_conflicts += 1
            for row in image_rows:
                issue = "conflicting_duplicate_image"
                row_issues[(row.split, row.line_no)].append(issue)
                issue_counter[issue] += 1

    train_orders = {row.meta.get("order_id") for row in rows if row.split == "train" and row.meta.get("order_id")}
    val_orders = {row.meta.get("order_id") for row in rows if row.split == "val" and row.meta.get("order_id")}
    shared_orders = sorted(train_orders & val_orders)
    shared_lookup = set(shared_orders)
    if shared_lookup:
        for row in rows:
            if row.meta.get("order_id") in shared_lookup:
                issue = "shared_order_id_between_train_val"
                row_issues[(row.split, row.line_no)].append(issue)
                issue_counter[issue] += 1

    for row in rows:
        key = (row.split, row.line_no)
        for issue in sorted(set(row_issues.get(key, []))):
            flagged_rows.append(
                {
                    "issue": issue,
                    "split": row.split,
                    "line_no": row.line_no,
                    "image": row.image,
                    "order_id": row.meta.get("order_id", ""),
                    "scene_id": row.meta.get("scene_id", ""),
                    "label": row.label,
                }
            )

    summary = {
        "total_rows": len(rows),
        "split_counts": dict(Counter(row.split for row in rows)),
        "status_counts": dict(status_counter),
        "skip_reason_counts": dict(skip_counter),
        "issue_counts": dict(issue_counter),
        "conflicting_duplicate_images": duplicate_conflicts,
        "shared_order_ids_between_train_val": len(shared_orders),
        "shared_order_ids_sample": shared_orders[:50],
    }
    return summary, row_issues, flagged_rows


