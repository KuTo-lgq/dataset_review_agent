"""Unified dataset audit pipeline for structured vision datasets.

This pipeline is designed for datasets whose labels already exist, including
datasets that were originally generated by a large model. The program does not
treat the upstream labeling model as the final judge. Instead it combines:

1. Static schema validation
2. Intra-label consistency checks
3. Cross-sample consistency checks
4. Optional model-assisted risk discovery
5. Unified risk ranking
6. Manual review pack generation
7. Markdown report generation
"""

